"""Тауар атауынан тауар тобын, плитка форматын және бонус санатын анықтау."""
from __future__ import annotations

import re

TILE = "Плитка / керамогранит"
DELIVERY = "Жеткізу (доставка)"
SERVICES = "Қызметтер"

# Реті маңызды: бірінші сәйкес келген ереже қолданылады.
KIND_RULES = [
    (DELIVERY, r"доставк"),
    (SERVICES, r"упаковк|услуг|монтаж|распил|резк|подъ[её]м|разгрузк|погрузк"),
    ("Смесительдер", r"смесител"),
    ("Унитаз / инсталляция", r"унитаз|инсталляц|биде|писсуар"),
    ("Раковина / тумба", r"раковин|тумб|умывальн|мойк"),
    ("Душ кабиналары", r"душев\w* кабин|душев\w* уголок|душев\w* двер|поддон"),
    ("Айналар", r"зеркал"),
    ("Душ жабдықтары", r"душев|душ\b|лейк|гарнитур|тропическ"),
    ("Сифон / клапан", r"сифон|клапан|гофр|трап\b"),
    ("Ванна аксессуарлары", r"полотенце|крюч|ершик|стакан|полк|кольц|подстаканник|держател|корзин|штанг|мыльниц|дозатор|бумагодерж"),
    ("Ванналар", r"\bванна\b"),
    (TILE, r"плитк|плиты|плита\b|керамогранит|кафель|мозаик|бордюр|декор|панно|ступен|клинкер|керамич"),
    ("Құрылыс қоспалары", r"кле[йя]|затирк|грунт|гидроизоляц|герметик|крестик|свп\b|выравнива"),
]
_COMPILED = [(k, re.compile(p, re.IGNORECASE)) for k, p in KIND_RULES]

FMT_RE = re.compile(r"(\d{2,3})\s*[\*xXхХ×]\s*(\d{2,3})")
SEG_RE = re.compile(r"^(\d+)\s*-?\s*а?я\s+категори", re.IGNORECASE)

SANITARY = {
    "Смесительдер", "Унитаз / инсталляция", "Раковина / тумба", "Душ кабиналары",
    "Айналар", "Душ жабдықтары", "Сифон / клапан", "Ванна аксессуарлары", "Ванналар",
}


def kind_of(item: str) -> str:
    for kind, rx in _COMPILED:
        if rx.search(item):
            return kind
    return "Басқа тауарлар"


def tile_format(item: str) -> str:
    m = FMT_RE.search(item)
    return f"{m.group(1)}×{m.group(2)}" if m else "Белгісіз"


def segment_label(segment: str) -> str:
    s = (segment or "").strip()
    if not s:
        return "Сегментсіз"
    m = SEG_RE.match(s)
    if m:
        return f"{m.group(1)}-санат"
    return s


def unit_of(kind: str) -> str:
    return "м²" if kind == TILE else "дана"
